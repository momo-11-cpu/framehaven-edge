import { readFile,writeFile,mkdir } from 'node:fs/promises';
export const vertex = `
struct Vertex { @builtin(position) position: vec4<f32>, @location(0) uv:vec2<f32> }
@vertex fn vs(@builtin(vertex_index) i:u32)->Vertex {
  let p=array<vec2<f32>,3>(vec2<f32>(-1.,-1.),vec2<f32>(3.,-1.),vec2<f32>(-1.,3.));
  var o:Vertex; o.position=vec4<f32>(p[i],0.,1.);o.uv=vec2<f32>((p[i].x+1.)*.5,(1.-p[i].y)*.5); return o;
}`;
export function convert(source){
  const parts=source.split('//!DESC ').slice(1);
  return parts.map((part,index)=>{
    const name=part.split('\n')[0].trim();
    const binds=[...part.matchAll(/\/\/!BIND (\w+)/g)].map(m=>m[1]);
    const save=part.match(/\/\/!SAVE (\w+)/)?.[1]??'MAIN';
    const shared=`${vertex}
@group(0) @binding(0) var input0:texture_2d<f32>;
@group(0) @binding(1) var original:texture_2d<f32>;
@group(0) @binding(2) var smp:sampler;
struct Settings { strength:f32, unused0:f32, unused1:f32, unused2:f32 }
@group(0) @binding(3) var<uniform> settings:Settings;
var<private> pixel:vec2<i32>;
fn sampleOffset(x:f32,y:f32)->vec4<f32>{
 let p=clamp(pixel+vec2<i32>(i32(x),i32(y)),vec2<i32>(0),vec2<i32>(textureDimensions(input0))-vec2<i32>(1));
 return textureLoad(input0,p,0);
}`;
    if(name.includes('Depth-to-Space'))return {name,binds,save,scale:2,code:shared+`
@fragment fn fs(@builtin(position) p:vec4<f32>,@location(0) uv:vec2<f32>)->@location(0) vec4<f32>{
 let pos=vec2<i32>(p.xy); let low=pos/2; let channel=u32(pos.y%2*2+pos.x%2);
 let residual=textureLoad(input0,low,0)[channel];
 let rgb=textureSampleLevel(original,smp,uv,0.).rgb+vec3<f32>(residual);
 return vec4<f32>(rgb,1.);
}`};
    let body=part.match(/vec4 hook\(\)\s*\{([\s\S]*)\}/)?.[1];
    if(!body)throw Error(`Missing hook: ${name}`);
    const activated=/#define go_0.*max\(/.test(part);
    const final=save==='MAIN';
    body=body.replace(/mat4\(/g,'mat4x4<f32>(').replace(/vec4\(/g,'vec4<f32>(')
      .replace('vec4 result =','var result:vec4<f32> =')
      .replace(/MAIN_tex\(MAIN_pos\)/g,'textureLoad(original,pixel,0)');
    if(final)body=body.replace(/return result \+ textureLoad\(original,pixel,0\);/,
      'return vec4<f32>(mix(textureLoad(original,pixel,0).rgb,(result+textureLoad(original,pixel,0)).rgb,settings.strength),1.);');
    return {name,binds,save,scale:1,code:shared+`
fn go_0(x:f32,y:f32)->vec4<f32>{return ${activated?'max(sampleOffset(x,y),vec4<f32>(0.))':'sampleOffset(x,y)'};}
fn go_1(x:f32,y:f32)->vec4<f32>{return max(-sampleOffset(x,y),vec4<f32>(0.));}
@fragment fn fs(@builtin(position) p:vec4<f32>,@location(0) uv:vec2<f32>)->@location(0) vec4<f32>{
 pixel=vec2<i32>(p.xy);${body}
}`};
  });
}
export async function generate(){
  const restore=convert(await readFile('vendor/anime4k-restore-s.glsl','utf8'));
  const upscale=convert(await readFile('vendor/anime4k-upscale-s.glsl','utf8'));
  await mkdir('src/generated',{recursive:true});
  await writeFile('src/generated/anime.ts',`// Derived from bloc97/Anime4K v4.0.1 (MIT). See THIRD_PARTY_NOTICES.md.\n// Generated by scripts/convert-anime.mjs; do not edit coefficients.\nexport const animeRestore = ${JSON.stringify(restore)};\nexport const animeUpscale = ${JSON.stringify(upscale)};\n`);
  console.log(`Anime4K: ${restore.length} restore passes, ${upscale.length} upscale passes`);
}
